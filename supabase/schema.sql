-- PANGAN PAS schema for Supabase (PostgreSQL).
-- Run this in Supabase Dashboard > SQL Editor before deploying the Vercel app.

create table if not exists public.pengguna (
  id bigint generated by default as identity primary key,
  auth_uid uuid not null unique references auth.users(id) on delete cascade,
  nama varchar(80) not null,
  username varchar(30) not null unique,
  email varchar(190) not null unique,
  tema text not null default 'terang' check (tema in ('terang','gelap')),
  notifikasi_harga boolean not null default false,
  akses_lokasi boolean not null default false,
  dibuat timestamptz not null default now(),
  diperbarui timestamptz not null default now(),
  login_terakhir timestamptz
);

create table if not exists public.lokasi_favorit (
  id bigint generated by default as identity primary key,
  pengguna_id bigint not null references public.pengguna(id) on delete cascade,
  provinsi varchar(60) not null,
  dibuat timestamptz not null default now(),
  unique (pengguna_id, provinsi)
);

create table if not exists public.pantauan_harga (
  id bigint generated by default as identity primary key,
  pengguna_id bigint not null references public.pengguna(id) on delete cascade,
  komoditas varchar(60) not null,
  wilayah varchar(60) not null,
  jenis_pasar text not null default 'tradisional' check (jenis_pasar in ('tradisional','modern')),
  arah text not null default 'keduanya' check (arah in ('naik','turun','keduanya')),
  tipe_batas text not null default 'persen' check (tipe_batas in ('persen','nominal')),
  nilai_batas numeric(12,2) not null,
  periode text not null default '7 hari' check (periode in ('7 hari','14 hari','30 hari')),
  aktif boolean not null default true,
  terakhir_dicek timestamptz,
  terakhir_dikirim timestamptz,
  tanggal_data_terkirim date,
  dibuat timestamptz not null default now()
);
create index if not exists idx_pantauan_pengguna on public.pantauan_harga (pengguna_id, aktif);

create table if not exists public.notifikasi_harga (
  id bigint generated by default as identity primary key,
  pengguna_id bigint not null references public.pengguna(id) on delete cascade,
  pantauan_id bigint references public.pantauan_harga(id) on delete set null,
  komoditas varchar(60) not null,
  wilayah varchar(60) not null,
  jenis_pasar text not null check (jenis_pasar in ('tradisional','modern')),
  harga_awal integer not null,
  harga_akhir integer not null,
  persen numeric(7,2) not null,
  periode varchar(16) not null,
  tanggal_awal date not null,
  tanggal_akhir date not null,
  sumber varchar(80) not null default 'PIHPS Nasional – Bank Indonesia',
  dibaca boolean not null default false,
  dibuat timestamptz not null default now()
);
create index if not exists idx_notif_pengguna on public.notifikasi_harga (pengguna_id, dibuat desc);

create table if not exists public.kiriman_harga (
  id bigint generated by default as identity primary key,
  pengguna_id bigint references public.pengguna(id) on delete set null,
  nama_kontributor varchar(48) not null,
  komoditas varchar(60) not null,
  harga integer not null check (harga >= 500),
  satuan varchar(16) not null,
  jenis_tempat text not null check (jenis_tempat in ('Pasar tradisional','Supermarket')),
  nama_pasar_toko varchar(80) not null,
  provinsi varchar(60) not null,
  tanggal_pengamatan date not null,
  catatan varchar(240),
  foto_path varchar(255),
  status_verifikasi text not null default 'belum_diverifikasi' check (status_verifikasi in ('belum_diverifikasi','terverifikasi','ditolak')),
  waktu_kirim timestamptz not null default now()
);
create index if not exists idx_kiriman_waktu on public.kiriman_harga (waktu_kirim desc);
create index if not exists idx_kiriman_pengguna on public.kiriman_harga (pengguna_id);
create index if not exists idx_kiriman_komoditas_provinsi on public.kiriman_harga (komoditas, provinsi);

create table if not exists public.komentar (
  id bigint generated by default as identity primary key,
  kiriman_id bigint not null references public.kiriman_harga(id) on delete cascade,
  pengguna_id bigint references public.pengguna(id) on delete set null,
  nama varchar(48) not null default 'Pengunjung',
  isi varchar(240) not null,
  waktu_kirim timestamptz not null default now()
);
create index if not exists idx_komentar_kiriman on public.komentar (kiriman_id, waktu_kirim);

create table if not exists public.balasan (
  id bigint generated by default as identity primary key,
  komentar_id bigint not null references public.komentar(id) on delete cascade,
  pengguna_id bigint references public.pengguna(id) on delete set null,
  nama varchar(48) not null default 'Pengunjung',
  isi varchar(240) not null,
  waktu_kirim timestamptz not null default now()
);
create index if not exists idx_balasan_komentar on public.balasan (komentar_id, waktu_kirim);

-- All application data is accessed through same-origin Vercel functions using the
-- server-only service-role key. Enable RLS as a second line of defense against
-- accidental client access; do not add anon/authenticated write policies here.
alter table public.pengguna enable row level security;
alter table public.lokasi_favorit enable row level security;
alter table public.pantauan_harga enable row level security;
alter table public.notifikasi_harga enable row level security;
alter table public.kiriman_harga enable row level security;
alter table public.komentar enable row level security;
alter table public.balasan enable row level security;

